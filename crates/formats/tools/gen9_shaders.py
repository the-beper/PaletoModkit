#!/usr/bin/env python3
"""Writes crates/formats/src/gen9_shaders.txt, the table the CodeWalker XML export uses
to give the parameters of Enhanced shaders their Legacy names.

The source is CodeWalker's ShadersGen9Conversion.xml (MIT). Only what the export needs
is kept: the shader names, and for each Texture or CBuffer parameter that has an `old=`
attribute its Enhanced name and Legacy name. Types, buffers and offsets are not kept:
the game files hold them.

    python3 crates/formats/tools/gen9_shaders.py \
        third_party/codewalker/CodeWalker.Core/ShadersGen9Conversion.xml \
        > crates/formats/src/gen9_shaders.txt
"""

import sys
import xml.etree.ElementTree as ET
from collections import Counter, defaultdict

HEADER = """\
# Enhanced shader parameters and their Legacy names, from CodeWalker's
# ShadersGen9Conversion.xml (MIT). Generated by crates/formats/tools/gen9_shaders.py.
# "enhanced<TAB>legacy": the usual Legacy name of an Enhanced parameter.
# "@shader<TAB>exception...": a shader the conversion knows, with the parameters it
# maps otherwise: "enhanced=legacy" for another name, a bare "enhanced" for none."""


def main() -> None:
    root = ET.parse(sys.argv[1]).getroot()
    shaders = []  # (name, {enhanced lower: legacy or None})
    uses: dict[str, Counter] = defaultdict(Counter)
    spelling = {}
    for item in root.findall("Item"):
        params = {}
        for p in item.find("Parameters"):
            if p.get("type") not in ("Texture", "CBuffer"):
                continue
            name, old = p.get("name"), p.get("old")
            assert old is None or not old.startswith("hash_"), old
            params.setdefault(name.lower(), old)
            if old is not None:
                uses[name.lower()][old] += 1
                spelling.setdefault(name.lower(), name)
        shaders.append((item.findtext("Name"), params))
    # The most common Legacy name of each Enhanced name.
    common = {lower: olds.most_common(1)[0][0] for lower, olds in uses.items()}
    print(HEADER)
    for lower in sorted(common):
        print(f"{spelling[lower]}\t{common[lower]}")
    for shader, params in shaders:
        exceptions = []
        for lower, old in params.items():
            # The name each would give (no Legacy name keeps the Enhanced one).
            if (old or lower).lower() == common.get(lower, lower).lower():
                continue
            name = spelling.get(lower, lower)
            exceptions.append(name if old is None else f"{name}={old}")
        print("\t".join([f"@{shader}", *exceptions]))


if __name__ == "__main__":
    main()
